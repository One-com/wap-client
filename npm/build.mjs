/**
 * npm build — generates dist/ from the canonical widget assets.
 *
 * The single source of truth for the chat widget is assets/wap-chat.{js,css}
 * (shared with the WordPress Composer package and, via
 * py-backend/scripts/sync_wap_client_assets.sh, the backend admin tester).
 * dist/ is NEVER committed — it is rebuilt on every `npm pack`/`npm publish`
 * (prepack hook), so the npm tarball cannot drift from the canonical assets.
 *
 * Outputs:
 *   dist/wap-chat.css     verbatim copy (import '@group-one/wap-client/widget.css')
 *   dist/wap-chat.js      verbatim copy — classic script-tag build (window.WapChat)
 *   dist/widget.esm.js    ESM entry — wraps the canonical IIFE in a lazy boot()
 *                         so importing is SSR-safe (no window/document access
 *                         until init() is called in a browser)
 *   dist/widget.d.ts      TypeScript definitions (hand-written in npm/widget.d.ts)
 *   dist/vendor/          vendored Mixpanel loader + SDK (verbatim copies) for
 *                         hosts that enable client-side analytics; the host
 *                         serves them and points mixpanelLoaderUrl /
 *                         mixpanelLibUrl at them
 *
 * Zero dependencies by design: plain Node ≥ 18, no bundler, nothing to install.
 */

import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

// ---------------------------------------------------------------------------
// Version guard: package.json must match the plugin header in wap-client.php.
// A mismatch means someone bumped one manifest and forgot the other — fail
// loudly rather than publish an npm version that lies about its contents.
// ---------------------------------------------------------------------------

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const phpHeader = readFileSync(join(root, 'wap-client.php'), 'utf8');
const phpVersion = (phpHeader.match(/^\s*\*\s*Version:\s*([0-9][0-9a-zA-Z.\-]*)\s*$/m) || [])[1];

if (!phpVersion) {
    console.error('build: could not parse the Version header from wap-client.php');
    process.exit(1);
}
// CI publishes prerelease builds from develop (e.g. 2.1.0-dev.42) by suffixing
// the version at publish time; the PHP header only ever carries the base
// X.Y.Z, so the guard compares against that.
const baseVersion = pkg.version.split('-')[0];
if (phpVersion !== baseVersion) {
    console.error(
        `build: version mismatch — package.json is ${pkg.version} (base ${baseVersion}) ` +
        `but wap-client.php header is ${phpVersion}. Bump both together before publishing.`
    );
    process.exit(1);
}

// ---------------------------------------------------------------------------
// Build
// ---------------------------------------------------------------------------

mkdirSync(dist, { recursive: true });

copyFileSync(join(root, 'assets', 'wap-chat.css'), join(dist, 'wap-chat.css'));
copyFileSync(join(root, 'assets', 'wap-chat.js'), join(dist, 'wap-chat.js'));
copyFileSync(join(root, 'npm', 'widget.d.ts'), join(dist, 'widget.d.ts'));
copyFileSync(join(root, 'npm', 'server.mjs'), join(dist, 'server.js'));
copyFileSync(join(root, 'npm', 'server.d.ts'), join(dist, 'server.d.ts'));

// Vendored Mixpanel SDK — the host serves these itself and points
// mixpanelLoaderUrl / mixpanelLibUrl at them. Without them in the tarball the
// widget's trackingInit() has nothing to load and client-side analytics stays
// silently disabled for npm consumers.
//
// The README ships with them on purpose: the tarball redistributes an Apache-2.0
// library, so the notice (package, version, hashes, our modifications) travels
// with it, and a consumer serving the blob can answer for what it is. It is kept
// free of repo-internal detail for that reason — maintenance lives in
// docs/vendoring-mixpanel.md.
mkdirSync(join(dist, 'vendor'), { recursive: true });
copyFileSync(
    join(root, 'assets', 'vendor', 'mixpanel-loader.js'),
    join(dist, 'vendor', 'mixpanel-loader.js')
);
copyFileSync(
    join(root, 'assets', 'vendor', 'mixpanel.min.js'),
    join(dist, 'vendor', 'mixpanel.min.js')
);
copyFileSync(
    join(root, 'assets', 'vendor', 'README.md'),
    join(dist, 'vendor', 'README.md')
);

const source = readFileSync(join(root, 'assets', 'wap-chat.js'), 'utf8');

const esm = `/**
 * @group-one/wap-client — ESM widget entry. GENERATED by npm/build.mjs from
 * assets/wap-chat.js (v${pkg.version}); do not edit. The canonical IIFE is
 * deferred inside boot() so this module is safe to import during SSR — no
 * window/document access happens until init() runs in a browser.
 */

function boot() {
${source}
}

let booted = false;

function ensureBooted(options, entry) {
    if (typeof window === 'undefined' || typeof document === 'undefined') {
        throw new Error('@group-one/wap-client/widget is browser-only — call ' + entry + '() from browser code, not during SSR.');
    }
    // Seed the config BEFORE the first boot: the canonical script registers a
    // DOMContentLoaded auto-init, so options must be visible to it in case
    // that listener fires before (or instead of) our explicit init call.
    // That auto-init stands down once init()/mount() has run explicitly, so a
    // mount() before the document finishes parsing does not get a second,
    // root-less init() at DOMContentLoaded.
    // The package version is baked in as a default (WordPress injects it via
    // wp_localize_script; npm consumers get it from the build) — an explicit
    // options.version still wins.
    window.WapClientConfig = Object.assign({ version: '${pkg.version}' }, window.WapClientConfig || {}, options || {});
    if (!booted) {
        boot();
        booted = true;
    }
}

export function init(options) {
    ensureBooted(options, 'init');
    return window.WapChat.init(options);
}

/**
 * Mount the widget as a collapsible docked column inside \`target\`.
 * Returns a handle: {expand, collapse, toggle, isCollapsed, destroy, root},
 * or null when \`target\` cannot be resolved.
 */
export function mount(target, options) {
    ensureBooted(options, 'mount');
    return window.WapChat.mount(target, options);
}

/**
 * Tear the widget down and release listeners — call this on SPA unmount.
 * \`booted\` deliberately stays true: the canonical script is still loaded and
 * window.WapChat is still wired, so a later init()/mount() must reuse it rather
 * than evaluate the IIFE a second time. Do not "fix" this to reset the flag.
 */
export function destroy() {
    if (!booted || !window.WapChat) return;
    return window.WapChat.destroy();
}

export default { init, mount, destroy };
`;

writeFileSync(join(dist, 'widget.esm.js'), esm);

console.log(`build: dist/ generated for @group-one/wap-client@${pkg.version} (canonical assets v${phpVersion})`);
